-- 0107: recorte fuerte de la XP: misiones a un tercio, las de quedar entre los primeros a una
-- sexta parte, minijuegos casi sin XP diaria, y lo ya reclamado se recalcula con los valores nuevos.
--
-- REQUIERE 0106 (misiones_catalogo).
--
-- Por qué: los niveles subían demasiado rápido. La XP de las misiones era alta y, al ser
-- retroactivas, tres cuentas cobraron 5.310 XP el primer día (hasta el nivel 14). Y los minijuegos
-- daban hasta 30 XP al día, más que entrar cada día.
--
-- Cambios:
--   1) misiones_catalogo(): la XP de TODOS los escalones se divide entre 3 (mínimo 5 XP). Las
--      misiones de quedar entre los primeros (Top 10, Podio, En lo más alto, Líder de la general,
--      Presencia, Rey de la liga, Top del ranking de minijuegos y Primero del día) se dividen
--      además entre 2: una sexta parte de la XP anterior. Los objetivos no cambian.
--   2) Minijuegos: variables del panel (game_config) mj_xp_por_juego 3 -> 1, mj_tope_xp_dia 20 -> 4
--      y mj_cofre_xp 10 -> 2. Como mucho 6 XP al día (antes 30). La XP de minijuegos ya ganada
--      (697 XP entre todos) no se toca.
--   3) Lo ya reclamado se recalcula: cada escalón reclamado (xp_movimientos, fuente 'mision') pasa
--      a valer lo que paga ahora ese escalón, con fijar_xp, que aplica solo la diferencia al total
--      del usuario. Los niveles de quien tenga XP de misiones bajarán en consecuencia (la XP
--      de login, cofre, jornada y minijuegos no cambia). NO se tocan los 4 reclamos de la primera
--      versión de misiones (0102: clausulazo:1, elo:1, racha:1, racha:2, 240 XP): sus series ya no
--      existen en el catálogo, y tampoco los de series que se hayan quitado (pujas_pub).
--      Los iconos de perfil que alguien ya tuviera elegidos se quedan puestos aunque su nivel
--      baje: solo impiden elegir otros nuevos hasta recuperar el nivel.
--
-- Impacto en datos existentes: SÍ modifica XP de usuarios (xp_usuarios y xp_movimientos de misiones,
-- hacia abajo) y dos variables de configuración. Hoy afecta a 3 cuentas con misiones reclamadas.
-- Lanzar con `supabase db push` o en el SQL Editor.


