-- 2) Minijuegos: casi sin XP diaria -------------------------------------------------------------
insert into public.game_config (clave, valor) values
  ('mj_xp_por_juego', '1'::jsonb),
  ('mj_tope_xp_dia', '4'::jsonb),
  ('mj_cofre_xp', '2'::jsonb)
on conflict (clave) do update set valor = excluded.valor, updated_at = now();


-- 3) Lo ya reclamado vale lo que paga ahora ------------------------------------------------------
do $$
declare
  r record;
begin
  for r in
    select m.user_id, m.clave, k.xp
    from public.xp_movimientos m
    join public.misiones_catalogo() k
      on k.serie = split_part(m.clave, ':', 1)
     and k.nivel::text = split_part(m.clave, ':', 2)
    where m.fuente = 'mision' and m.cantidad <> k.xp
  loop
    perform public.fijar_xp(r.user_id, 'mision', r.clave, r.xp);
  end loop;
end;
$$;
