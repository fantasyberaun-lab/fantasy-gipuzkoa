-- de la carga provisional de 0006_seed_players.sql.
--
-- Qué hace:
--   - Añade a `players` las columnas `sexo` ('M' / 'F') y `edad` (años
--     cumplidos en 2026, tal cual la calcula el Excel: 2026 - año de
--     nacimiento).
--   - Vacía `players` y carga los 574 jugadores del Excel con todos sus
--     datos: nombre, club, categoría, Elo, ID FIDE, año de nacimiento, edad
--     y sexo.
--   - Categoría: PREFERENTE y PRIMERA -> '1', SEGUNDA -> '2', TERCERA -> '3'
--     (mismo criterio que 0006).
--   - Elo = 0 significa "sin Elo todavía" (igual que antes).
--   - El valor de mercado se calcula con la fórmula de 0010
--     (calcular_valor_inicial), no con la provisional elo/45 de 0006.
--   - Se han quitado 8 filas repetidas al 100% del Excel (mismo nombre,
--     ID FIDE, club y categoría).
--
-- Sobre la edad: la fórmula de valor (0010) calcula la edad como
-- (año actual - anio_nacimiento), así que hoy da el mismo resultado que la
-- columna `edad`. Ojo: `edad` es un dato guardado y no se actualiza sola al
-- cambiar de año; `anio_nacimiento` sí permite recalcularla siempre.
--
-- ATENCIÓN: `truncate ... cascade` borra también todo lo que apunta a
-- players (plantillas/squad_slots, resultados, listings de mercado, pujas,
-- ofertas, jugadores de torneos...). Úsalo solo mientras haya datos de
-- prueba. Los usuarios, equipos Fantasy y ligas se conservan, pero sus
-- plantillas quedarán vacías.

